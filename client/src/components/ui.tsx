import { useEffect, type ReactNode } from 'react';
import { initials, SEVERITY_LABEL, STATUS_LABEL, userColor } from '../lib/format';

export function Modal({
  title,
  onClose,
  children,
  footer,
  wide,
}: {
  title: string;
  onClose: () => void;
  children: ReactNode;
  footer?: ReactNode;
  wide?: boolean;
}) {
  useEffect(() => {
    const onKey = (e: KeyboardEvent) => e.key === 'Escape' && onClose();
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, [onClose]);
  return (
    <div className="modal-backdrop" onMouseDown={(e) => e.target === e.currentTarget && onClose()}>
      <div className={`modal ${wide ? 'wide' : ''}`} role="dialog" aria-modal aria-label={title}>
        <div className="modal-head">
          <h2>{title}</h2>
          <button className="icon-btn" onClick={onClose} aria-label="Close">
            ×
          </button>
        </div>
        <div className="modal-body">{children}</div>
        {footer && <div className="modal-foot">{footer}</div>}
      </div>
    </div>
  );
}

export function Avatar({
  id,
  name,
  size = 24,
  speaking,
  muted,
}: {
  id: string;
  name: string;
  size?: number;
  speaking?: boolean;
  muted?: boolean;
}) {
  return (
    <span
      className={`avatar ${speaking ? 'speaking' : ''}`}
      style={{ width: size, height: size, fontSize: size * 0.42, background: userColor(id) }}
      title={name}
    >
      {initials(name)}
      {muted && <span className="avatar-muted" aria-label="muted">{Icons.micOff}</span>}
    </span>
  );
}

export function SeverityBadge({ severity, long }: { severity: string; long?: boolean }) {
  return (
    <span className={`sev sev-${severity.toLowerCase()}`}>
      <span className="sev-shape" aria-hidden />
      {severity}
      {long && <span className="sev-long"> · {SEVERITY_LABEL[severity]}</span>}
    </span>
  );
}

export function StatusPill({ status }: { status: string }) {
  return <span className={`status status-${status}`}>{STATUS_LABEL[status] ?? status}</span>;
}

